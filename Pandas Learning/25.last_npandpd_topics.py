# Data Cleaning Functions:
# df.drop_duplicates() → Pandas → removes duplicate rows.
# df.replace([np.inf, -np.inf], np.nan) → Pandas + NumPy → replaces +∞ and -∞ with NaN.
# df.fillna(df["column"].mean()) → Pandas → fills missing values with the column mean.
# np.where(condition, value_if_true, value_if_false) → NumPy → updates values based on a condition.
# np.mean() → NumPy → calculates the mean/average.
# np.std() → NumPy → calculates standard deviation.
# np.inf → NumPy → represents positive infinity.
# np.nan → NumPy → represents a missing/undefined numerical value.
