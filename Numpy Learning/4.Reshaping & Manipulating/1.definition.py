# What is Reshaping?

# Reshaping means changing the shape of arrays without changing their data.
# It is a way to reorganize the data in an array to fit a specific structure
# or format. Reshaping is commonly used in data analysis and machine learning
# to prepare data for modeling or visualization.
# with the help of reshaping, we can change the rows and columns of an array
# to create a new shape that is more suitable for our analysis or modeling needs.
# we can convert 1d to 2d, 2d to 3d, 3d to 1d and so on.
# No of elements in the array must remain the same after reshaping. For example,
# if we have an array with 12 elements, we can reshape it into a 3x4 array or a
# 4x3 array, but we cannot reshape it into a 2x5 array because that would require
# 10 elements.

