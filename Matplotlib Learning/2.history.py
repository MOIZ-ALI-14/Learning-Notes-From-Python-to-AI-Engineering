# ==============================================================
#                    MATPLOTLIB - HISTORY
# ==============================================================

# Matplotlib was created by John D. Hunter (1968–2012).
#
# Around 2002–2003, John Hunter was working with EEG
# (electroencephalography) data during scientific/medical research.
#
# He had been using MATLAB for data analysis and visualization,
# especially for creating plots.
#
# As his EEG project became more complex, he wanted to build
# interactive applications around his data and work more naturally
# with Python.
#
# At that time, Python did not have a 2D plotting library that
# fully matched what he needed.
#
# So John Hunter started developing a Python-based plotting
# solution with MATLAB-style graphics.
#
# This project became Matplotlib.
#
# Matplotlib officially appeared around 2003 and was initially
# focused on visualizing scientific data, including EEG data.
#
# Its design was influenced by MATLAB's plotting commands, but
# Matplotlib became an independent Python library.
#
# The name "Matplotlib" comes from:
#
#       MATLAB + plot + library
#
# Over time, Matplotlib grew from a project created for a
# scientific/EEG application into a general-purpose Python
# visualization library.
#
# Today, Matplotlib is widely used with Python, NumPy, Pandas,
# scientific computing, data analysis, and machine learning.
#
# The important history to remember is:
#
#       Scientific/EEG problem
#              ↓
#       Python needed better plotting
#              ↓
#       John D. Hunter created Matplotlib
#              ↓
#       MATLAB-style plotting in Python
#              ↓
#       Open-source Python visualization library
#
