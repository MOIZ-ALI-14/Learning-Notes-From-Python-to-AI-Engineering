# 1. Line Chart
# Use it when data changes over time or in an ordered sequence.
# Best for showing trends — increasing, decreasing, or fluctuating.
# X-axis usually represents time or another ordered variable.
# Great for comparing multiple trends on the same graph.
# Best choice: when you want to answer “How does this value change?”

# Example: monthly sales, temperature over a week, stock price over time.

# 📊 2. Bar Chart
# Use it to compare separate categories.
# Each category gets its own bar.
# The bar's height/length represents its value.
# Best when categories are independent, not a continuous sequence.
# Best choice: when you want to answer “Which category has more or less?”

# Example: sales of Mango, Apple, Banana, and Orange.

# 🥧 3. Pie Chart
# Use it to show parts of one complete whole.
# All slices together represent 100%.
# Each slice shows a category's share or percentage.
# Best with a small number of categories.
# Best choice: when you want to answer “How is the total divided?”

# Example: revenue contribution by provinces, company expenses by category.

# 📊 4. Histogram
# Use it to show the distribution of numerical data.
# Data is divided into ranges (bins).
# Bars touch each other because the ranges are continuous.
# Useful for seeing where most values are concentrated.
# Best choice: when you want to answer “How are these numerical values distributed?”

# Example: distribution of student marks, ages of customers, or salaries.

# Important: A histogram is not the same as a bar chart.
# Bar chart → categories.
# Histogram → numerical ranges.

# 🔵 5. Scatter Plot
# Use it to show the relationship between two numerical variables.
# Each dot represents one observation/data point.
# Useful for seeing whether two variables move together.
# Can reveal patterns such as positive, negative, or weak relationships.
# Best choice: when you want to answer “Is there a relationship between X and Y?”

# Example: study hours vs marks, advertising cost vs sales, height vs weight.

# 🧠 Quick memory trick
# Chart	Main purpose
# 📈 Line	Trend / change
# 📊 Bar	Compare categories
# 🥧 Pie	Parts of a whole
# 📊 Histogram	Distribution
# 🔵 Scatter	Relationship
