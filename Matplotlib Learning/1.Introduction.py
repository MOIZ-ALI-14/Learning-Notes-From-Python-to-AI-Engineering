# ==============================================================
#                    MATPLOTLIB - INTRODUCTION
# ==============================================================

# Matplotlib is a Python library used for data visualization.
#
# It helps us represent numerical data in a visual form so that
# patterns, trends, comparisons, and relationships are easier
# to understand.
#
# The main problem it solves is that raw numbers and tables can
# sometimes be difficult to understand just by reading them.
#
# For example, instead of reading monthly sales as numbers,
# we can visualize them in a graph and quickly see whether
# sales are increasing, decreasing, or changing.
#
# Matplotlib is commonly used with NumPy and Pandas:
#
# NumPy      → works with numerical data
# Pandas     → cleans and analyzes data
# Matplotlib → visualizes the results
#
# It is useful in data analysis, statistics, machine learning,
# science, engineering, finance, research, and education.
#
# Visualization is important because a suitable graph can make
# a relationship or pattern easier to understand than raw numbers.
#
# In simple words:
#
#       Data → Analysis → Visualization → Understanding
#
# Matplotlib is therefore an important tool for turning
# numerical results into clear and understandable visuals.
#
# ==============================================================


# ==============================================================
#                 WHAT CAN MATPLOTLIB DO?
# ==============================================================
#
# With Matplotlib, we can create different types of visualizations
# such as:
#
#   - Line charts
#   - Bar charts
#   - Pie charts
#   - Histograms
#   - Scatter plots
#
# We can also format and customize our graphs, such as changing:
#
#   - Line colors
#   - Line styles
#   - Line width
#   - Markers
#   - Figure size
#   - Titles and labels
#   - Legends
#   - Grid
#
# So Matplotlib is not only used to create a graph;
# we can also design and format the graph to make the information
# clearer and easier to understand.
#
# ==============================================================
