# Definition Of NUMPY

# numpy stands for Numerical Python. It is a powerful library in Python used for
# numerical computations and data manipulation. It provides support for large
# multi-dimensional arrays and matrices, along with a collection of mathematical
# functions to operate on these arrays efficiently.

# ===================================================================================

# Benefits

# 1. Speed is 50-to-100 times faster than Python lists for numerical operations due
# to its optimized C implementation.

# 2. Memory efficiency: NumPy arrays consume less memory than Python lists, making
# them more efficient for large datasets.

# 3. Easy Mathematical Operations: NumPy provides a wide range of mathematical
# functions that can be applied to arrays, making it easy to perform complex
# calculations.

# 4. Used in Data Science, Machine Learinig and AI, Stock Market and Finance,
# Medical Research, Image Processing

# ==================================================================================

# Comparison of python List and Numpy Array

# Speed: Numpy Array is 50-100x faster than python list

# memory: Numpy Array uses very less memory as compared to python list

# Calculations: python list needs loops and big logic but, numpy performs any
#               calculation instantly and efficiently.

# ==> If we are working with small datasets or in simple systems, then python lists
#      or loops would be beneficial there
# ==> However, if you are working in large datasets where millions of values exist,
#     then numpy would be definitely best choice.

# ==================================================================================

# important about numpy array

# When NumPy creates an array, it normally chooses one common dtype for the whole array.
# If the input contains mixed types, NumPy tries to find a dtype that can represent all
# of them, often converting the values in the process.
