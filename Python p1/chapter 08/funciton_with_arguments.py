# A function is a block of code that performs a specific task.
# Arguments are values that we pass into a function so it can use
# those values to perform its task. Arguments work inside the
# function and help make the function flexible and reusable.


# function definition
def message(name, ending):
    print(f"Dear {name} \n How are you? \n {ending}")


# function call
message("Moiz", "Be Strong")
