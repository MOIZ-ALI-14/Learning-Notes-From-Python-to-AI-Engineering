import numpy as np

my_arr = np.array([1, 2, 3, 4, 5, 6])
print("addition", my_arr + 3)
print("subtraction", my_arr - 3)
print("multiplication", my_arr * 3)
print("division", my_arr / 3)
print("floor division", my_arr // 3)
print("square", my_arr**2)
print("remainder", my_arr % 3)

# we can perform mathematical operations on the arrays in just one line of code.
# For example, we can add 3 to each element of the array using the + operator.
# Similarly, we can subtract, multiply, divide, and perform other mathematical
# operations on the array elements.
